#!/usr/bin/env python3
"""Generate concrete Aurora PBS batch scripts with baked-in parameters.

The old workflow required env vars on qsub:

    NNODES=4 CASE=lid3d qsub batch/aurora_bench.sh

This generator bakes every parameter into the script itself so submission is
just:

    qsub batch/generated/lid2d_2048_2nodes.sh

No env vars, no CLI forwarding, no -- after qsub.

Stages
------
Each script can include any combination of three stages (in order):

  compiling    build bench (+ validate) exes with MPI+SYCL
  validating   run correctness checks (priority: this repo's benchmarks/*/validate
               over external/muphfasa/tests/regression/*)
  performance  run bench.cpp for MLUPS and log via perf.py

Pick stages with --stages. Default is all three. Examples:

    # Full pipeline (compile + validate + perf) — default
    python3 batch/generate.py --case lid2d --nodes 2 --size 2048

    # Perf only (assumes already built)
    python3 batch/generate.py --case lid2d --nodes 4 --size 4096 --stages performance

    # Just compile
    python3 batch/generate.py --case lid3d --nodes 4 --stages compiling

    # Compile + validate, skip perf
    python3 batch/generate.py --case lid2d --nodes 2 --stages compiling validating

    # Explicit all
    python3 batch/generate.py --case lid2d --nodes 2 --stages compiling validating performance

Usage (other):
    python3 batch/generate.py --case lid2d --nodes 2 4 --size 2048 --lattice D2Q9
    python3 batch/generate.py --case lid2d --nodes 2 4 --sizes 2048 4096
    python3 batch/generate.py --case lid3d --nodes 4 --size 256 --lattice D3Q19
    python3 batch/generate.py --case lid2d --nodes 2 4 --sizes 2048 4096 --no-product  # zipped
    python3 batch/generate.py --case lid2d --nodes 2 --queue prod --walltime 00:30:00 --project ABC123
"""

import argparse
import itertools
import os
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]

CASE_DIM = {
    "tgv2d": 2, "lid2d": 2,
    "tgv3d": 3, "lid3d": 3, "beltrami3d": 3,
}
CASE_LATTICE = {
    "tgv2d": "D2Q9", "lid2d": "D2Q9",
    "tgv3d": "D3Q19", "lid3d": "D3Q19", "beltrami3d": "D3Q19",
}

# Validate location per case: (local_path, external_fallback)
# Priority to this repo per user request.
VALIDATE_MAP = {
    "tgv2d":      ("benchmarks/tgv2d/validate",       "external/muphfasa/tests/regression/tgv2d"),
    "tgv3d":      ("benchmarks/tgv3d/validate",       None),
    "lid2d":      ("benchmarks/lid2d/validate",       "external/muphfasa/tests/regression/lid_driven_cavity"),
    "lid3d":      (None,                               None),  # no validate available
    "beltrami3d": ("benchmarks/beltrami3d/validate",  None),
}

ALL_STAGES = ["compiling", "validating", "performance"]

HEADER_TMPL = """#!/bin/bash -l
#PBS -l select={nodes}:system=aurora
#PBS -l walltime={walltime}
#PBS -l filesystems=flare
#PBS -q {queue}
#PBS -A {project}
#PBS -N {job_name}
# Generated by batch/generate.py — do not hand-edit (re-generate instead).
#   case={case} size={size} lattice={lattice} nodes={nodes} ppn={ppn} dim={dim} stages={stages_str}
# Submit with: qsub {out_rel}

set -e
cd ${{PBS_O_WORKDIR:-$(dirname $0)/../..}}

# Baked-in parameters (no env vars needed)
CASE="{case}"
SIZE="{size}"
LATTICE="{lattice}"
NNODES={nodes}
PPN={ppn}
DIM={dim}
NCELLS="{ncells}"
STAGES="{stages_str}"

echo "Aurora bench: case=$CASE size=$SIZE lattice=$LATTICE nodes=$NNODES ppn=$PPN dim=$DIM ncells=$NCELLS stages=$STAGES"
echo "Job: $PBS_JOBID on $(hostname) at $(date)"

if command -v module &>/dev/null; then
  module use /soft/modulefiles || true
  module load cmake || true
fi

export MPICH_GPU_SUPPORT_ENABLED=1
export FI_CXI_ATS=0
export ZE_FLAT_DEVICE_HIERARCHY=COMPOSITE
export OMP_NUM_THREADS=1
export HTTP_PROXY=http://proxy.alcf.anl.gov:3128
export HTTPS_PROXY=http://proxy.alcf.anl.gov:3128
export http_proxy=http://proxy.alcf.anl.gov:3128
export https_proxy=http://proxy.alcf.anl.gov:3128

"""

# These blocks go through .format(validate_compile=...) / .format(validate_run=...)
# so shell ${VAR} must be written as ${{VAR}} to survive Python formatting.
COMPILING_BLOCK = """
# ── Stage: compiling ──────────────────────────────────────────────────
echo "=== COMPILING $CASE (DIM=$DIM) ==="
make -C benchmarks/$CASE -j4 DIM=$DIM USE_MPI=TRUE USE_SYCL=TRUE COMP=intel
echo "Built benchmarks/$CASE/bench${{DIM}}d.*.ex"
{validate_compile}
echo "Compile stage done."
"""

VALIDATE_COMPILE_SNIPPET = """if [ -d "{validate_dir}" ]; then
  make -C {validate_dir} -j4 DIM=$DIM USE_MPI=TRUE USE_SYCL=TRUE COMP=intel || make -C {validate_dir} -j4 DIM=$DIM
  echo "Built {validate_dir}/test_*.ex"
fi"""

VALIDATING_BLOCK = """
# ── Stage: validating ─────────────────────────────────────────────────
echo "=== VALIDATING $CASE ==="
{validate_run}
echo "Validate stage done."
"""

VALIDATE_RUN_KNOWN = """if [ -d "{validate_dir}" ]; then
  echo "Running validate from {validate_dir} (priority: this repo)"
  VALIDATE_EXE=$(ls {validate_dir}/test_*.ex {validate_dir}/*.ex 2>/dev/null | head -1)
  if [ -z "$VALIDATE_EXE" ]; then
    echo "ERROR: no validate exe in {validate_dir} — did compiling stage run?"; exit 1
  fi
  echo "Validate exe: $VALIDATE_EXE"
  # Validate runs are small (N=32-64) — single rank is sufficient
  if [ "$NNODES" -gt 1 ]; then
    mpiexec -n 1 --ppn 1 $VALIDATE_EXE {validate_dir}/inputs 2>&1 | tee validate_${{CASE}}_${{SIZE}}.log
  else
    $VALIDATE_EXE {validate_dir}/inputs 2>&1 | tee validate_${{CASE}}_${{SIZE}}.log
  fi
  echo "Validate log: validate_${{CASE}}_${{SIZE}}.log"
else
  echo "No validate directory for $CASE at {validate_dir} — skipping"
fi"""

VALIDATE_RUN_NONE = """echo "No validate available for $CASE — skipping (no benchmarks/$CASE/validate nor external fallback)" """

# Performance block is appended verbatim (not .format'd), so shell vars use single braces.
PERFORMANCE_BLOCK = """
# ── Stage: performance ────────────────────────────────────────────────
echo "=== PERFORMANCE $CASE size=$SIZE lattice=$LATTICE nodes=$NNODES ==="

# Fallback build if compiling stage was not included and exe is missing
if [ ! -f "benchmarks/$CASE/bench3d.gnu.ex" ] && [ ! -f "benchmarks/$CASE/bench2d.gnu.ex" ]; then
  echo "WARNING: bench exe not found — building on compute node (prefer compiling stage)"
  make -C benchmarks/$CASE -j4 DIM=$DIM USE_MPI=TRUE USE_SYCL=TRUE COMP=intel
fi

BENCH_EXE=$(ls benchmarks/$CASE/bench*.ex benchmarks/$CASE/*.ex 2>/dev/null | head -1)
if [ -z "$BENCH_EXE" ]; then echo "ERROR: no bench exe found"; exit 1; fi
INPUTS=benchmarks/$CASE/inputs.bench
RUN_DIR=run_${CASE}_${SIZE}_${NNODES}

echo "Bench exe: $BENCH_EXE"
echo "Inputs: $INPUTS  ncells=$NCELLS"

# GPU binding per https://docs.alcf.anl.gov/aurora/running-jobs-aurora/#binding-mpi-ranks-to-gpus
# Each Aurora node has 6 PVC GPUs x 2 tiles = 12 tiles. PPN=12 is "explicit scaling"
# (1 rank/tile) via gpu_tile_compact.sh; PPN=6 is "implicit" (1 rank/GPU) via
# gpu_dev_compact.sh. The wrapper sets ZE_AFFINITY_MASK per rank (requires
# ZE_FLAT_DEVICE_HIERARCHY=COMPOSITE, the Aurora default). The --cpu-bind list
# below reserves cores 0 and 52 for the OS (Mar 2025+) and gives each rank
# compact cores on its socket.
if [ "$PPN" -eq 12 ]; then
  CPU_BIND="--cpu-bind=list:1-8:9-16:17-24:25-32:33-40:41-48:53-60:61-68:69-76:77-84:85-92:93-100"
  GPU_WRAPPER="gpu_tile_compact.sh"
elif [ "$PPN" -eq 6 ]; then
  CPU_BIND="--cpu-bind=list:1-16:17-32:33-48:53-68:69-84:85-100"
  GPU_WRAPPER="gpu_dev_compact.sh"
else
  # Generic fallback: let MPICH place ranks, but still bind via wrapper
  CPU_BIND="--cpu-bind=depth --depth=8"
  GPU_WRAPPER="gpu_tile_compact.sh"
fi

mpiexec -n $((NNODES * PPN)) --ppn $PPN $CPU_BIND $GPU_WRAPPER \\
  $BENCH_EXE $INPUTS grid.ncells="$NCELLS" lbm.lattice_type=$LATTICE amr.plot_int=-1 2>&1 | tee $RUN_DIR.log

grep BENCH_RESULT $RUN_DIR.log || echo "No BENCH_RESULT found"

source $HOME/pyvenv_lbm/bin/activate
python3 "$(dirname "$0")/../../perf.py" log --test "$CASE" --lattice "$LATTICE" --ncells "$NCELLS" --nprocs $((NNODES * PPN)) --inputs "$INPUTS" --log "$RUN_DIR.log" || echo "perf log failed (non-main branch skips history.jsonl by design)"
echo "Performance stage done: $RUN_DIR.log"
"""


def resolve_validate_dir(case: str) -> str | None:
    local, fallback = VALIDATE_MAP.get(case, (None, None))
    if local and (REPO_ROOT / local).is_dir():
        return local
    if fallback and (REPO_ROOT / fallback).is_dir():
        return fallback
    return local or fallback


def parse_args():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--case", "--cases", dest="cases", nargs="+", required=True,
                   choices=list(CASE_DIM.keys()), help="benchmark case(s)")
    p.add_argument("--nodes", nargs="+", type=int, required=True, help="node count(s), e.g. --nodes 2 4")
    p.add_argument("--size", type=int, default=None, help="N per side (alias for --sizes with one value)")
    p.add_argument("--sizes", nargs="+", type=int, default=None, help="N per side, e.g. --sizes 2048 4096")
    p.add_argument("--lattice", type=str, default=None, help="lattice, e.g. D2Q9 (default per case)")
    p.add_argument("--ppn", type=int, default=12, help="ranks per node (default 12 = 6 GPUs x 2 tiles)")
    p.add_argument("--queue", type=str, default="prod", help="PBS queue (default prod; debug for 1-2 nodes)")
    p.add_argument("--walltime", type=str, default="00:30:00")
    p.add_argument("--project", type=str, default="muphfasa", help="ALCF project allocation")
    p.add_argument("--stages", nargs="+", choices=ALL_STAGES, default=ALL_STAGES,
                   help="which stages to include (default: all three; pick any subset in any order)")
    p.add_argument("--outdir", type=Path, default=REPO_ROOT / "batch" / "generated",
                   help="output directory (default batch/generated/)")
    p.add_argument("--product", action=argparse.BooleanOptionalAction, default=True,
                   help="cartesian product of --cases x --nodes x --sizes (default true); --no-product zips them")
    p.add_argument("--dry-run", action="store_true", help="print paths without writing")
    return p.parse_args()


def main():
    args = parse_args()

    seen = set()
    stages = []
    for s in args.stages:
        if s not in seen:
            seen.add(s)
            stages.append(s)
    if not stages:
        raise SystemExit("--stages requires at least one of: " + ", ".join(ALL_STAGES))
    order = {s: i for i, s in enumerate(ALL_STAGES)}
    stages_sorted = sorted(stages, key=lambda s: order[s])

    if args.sizes is not None:
        sizes = args.sizes
    elif args.size is not None:
        sizes = [args.size]
    else:
        sizes = [None]

    cases = args.cases
    nodes_list = args.nodes

    if args.product:
        combos = list(itertools.product(cases, nodes_list, sizes))
    else:
        max_len = max(len(cases), len(nodes_list), len(sizes))
        def broadcast(lst):
            if len(lst) == 1:
                return lst * max_len
            if len(lst) != max_len:
                raise SystemExit(f"--no-product requires equal lengths or singletons, got cases={cases} nodes={nodes_list} sizes={sizes}")
            return lst
        combos = list(zip(broadcast(cases), broadcast(nodes_list), broadcast(sizes)))

    args.outdir.mkdir(parents=True, exist_ok=True)
    written = []

    for case, nodes, size in combos:
        dim = CASE_DIM[case]
        lattice = args.lattice or CASE_LATTICE[case]
        if size is None:
            size = 64
        ncells = f"{size} {size}" if dim == 2 else f"{size} {size} {size}"
        validate_dir = resolve_validate_dir(case)

        stages_str = " ".join(stages_sorted)
        stages_tag = "" if set(stages_sorted) == set(ALL_STAGES) else "_" + "_".join(stages_sorted)
        job_name = f"{case}_{size}_{nodes}nodes{stages_tag}"
        fname = f"{case}_{size}_{nodes}nodes{stages_tag}.sh"
        out_path = args.outdir / fname
        out_rel = os.path.relpath(out_path, REPO_ROOT)

        blocks = []

        if "compiling" in stages_sorted:
            if validate_dir and (REPO_ROOT / validate_dir).is_dir():
                vcomp = VALIDATE_COMPILE_SNIPPET.format(validate_dir=validate_dir)
            else:
                vcomp = ""
            blocks.append(COMPILING_BLOCK.format(validate_compile=vcomp))

        if "validating" in stages_sorted:
            if validate_dir:
                vrun = VALIDATE_RUN_KNOWN.format(validate_dir=validate_dir)
            else:
                vrun = VALIDATE_RUN_NONE
            blocks.append(VALIDATING_BLOCK.format(validate_run=vrun))

        if "performance" in stages_sorted:
            blocks.append(PERFORMANCE_BLOCK)

        header = HEADER_TMPL.format(
            nodes=nodes, walltime=args.walltime, queue=args.queue, project=args.project,
            job_name=job_name, case=case, size=size, lattice=lattice, ppn=args.ppn,
            dim=dim, ncells=ncells, stages_str=stages_str, out_rel=out_rel,
        )
        content = header + "".join(blocks)
        if not content.endswith("\n"):
            content += "\n"

        if args.dry_run:
            print(f"[dry-run] would write {out_rel} stages={stages_str}")
            continue
        out_path.write_text(content)
        out_path.chmod(0o755)
        written.append(out_rel)
        print(f"Wrote {out_rel}  (case={case} size={size} nodes={nodes} lattice={lattice} stages={stages_str})")

    if written:
        print(f"\nSubmit with:  qsub {' '.join(written)}")
        print(f"Or individually: qsub {written[0]}")

if __name__ == "__main__":
    main()
