#!/usr/bin/env python3
"""Generate concrete Aurora PBS batch scripts with baked-in parameters.

The old workflow required env vars on qsub:

    NNODES=4 CASE=lid3d qsub batch/aurora_bench.sh

This generator bakes every parameter into the script itself so submission is
just:

    qsub batch/generated/lid2d_2048_2nodes.sh

No env vars, no CLI forwarding, no -- after qsub.

Stages
------
Each script can include any combination of three stages (in order):

  compiling    build bench (+ validate) exes with MPI+SYCL
  validating   run correctness checks (priority: external/muphfasa/tests/regression/*
               over this repo's benchmarks/*/validate when both exist)
  performance  run bench.cpp for MLUPS and log via perf.py

Pick stages with --stages. Default is all three. Examples:

    # Full pipeline (compile + validate + perf) — default
    python3 batch/generate.py --case lid2d --nodes 2 --size 2048

    # Perf only (assumes already built)
    python3 batch/generate.py --case lid2d --nodes 4 --size 4096 --stages performance

    # Just compile
    python3 batch/generate.py --case lid3d --nodes 4 --stages compiling

    # Compile + validate, skip perf
    python3 batch/generate.py --case lid2d --nodes 2 --stages compiling validating

    # Explicit all
    python3 batch/generate.py --case lid2d --nodes 2 --stages compiling validating performance

Usage (other):
    python3 batch/generate.py --case lid2d --nodes 2 4 --size 2048 --lattice D2Q9
    python3 batch/generate.py --case lid2d --nodes 2 4 --sizes 2048 4096
    python3 batch/generate.py --case lid3d --nodes 4 --size 256 --lattice D3Q19
    python3 batch/generate.py --case lid2d --nodes 2 4 --sizes 2048 4096 --no-product  # zipped
    python3 batch/generate.py --case lid2d --nodes 2 --queue prod --walltime 00:30:00 --project ABC123
"""

import argparse
import itertools
import os
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]

CASE_DIM = {
    "tgv2d": 2, "lid2d": 2,
    "tgv3d": 3, "lid3d": 3, "beltrami3d": 3,
    "couette2d": 2, "couette3d": 3,
    "poiseuille2d": 2, "poiseuille3d": 3,
    "uniform2d": 2, "uniform3d": 3,
}
CASE_LATTICE = {
    "tgv2d": "D2Q9", "lid2d": "D2Q9",
    "tgv3d": "D3Q19", "lid3d": "D3Q19", "beltrami3d": "D3Q19",
    "couette2d": "D2Q9", "couette3d": "D3Q19",
    "poiseuille2d": "D2Q9", "poiseuille3d": "D3Q19",
    "uniform2d": "D2Q9", "uniform3d": "D3Q19",
}

# Validate location per case: (primary, secondary)
# Primary is external/muphfasa/tests/regression/* when it exists (canonical);
# secondary is this repo's benchmarks/*/validate for custom checks (tgv3d,
# beltrami3d). User trusts upstream for lid2d etc., so external wins.
VALIDATE_MAP = {
    "tgv2d":        ("external/muphfasa/tests/regression/tgv2d",          None),
    "tgv3d":        ("benchmarks/tgv3d/validate",                           None),
    "lid2d":        ("external/muphfasa/tests/regression/lid2d",            None),
    "lid3d":        (None,                                                   None),  # no validate available
    "beltrami3d":   ("benchmarks/beltrami3d/validate",                       None),
    "couette2d":    ("external/muphfasa/tests/regression/couette",           None),
    "couette3d":    ("external/muphfasa/tests/regression/couette",           None),
    "poiseuille2d": ("external/muphfasa/tests/regression/poiseuille",        None),
    "poiseuille3d": ("external/muphfasa/tests/regression/poiseuille",        None),
    "uniform2d":    ("external/muphfasa/tests/regression/uniform_force",    None),
    "uniform3d":    ("external/muphfasa/tests/regression/uniform_force",    None),
}

ALL_STAGES = ["compiling", "validating", "performance"]

# Build options baked into scripts (must match exe naming via AMReX).
BUILD_COMP = "intel"
BUILD_USE_MPI = "TRUE"
BUILD_USE_SYCL = "TRUE"

DEFAULT_WARMUP = {2: 100, 3: 50}
DEFAULT_STEPS  = {2: 2000, 3: 500}

HEADER_TMPL = """#!/bin/bash -l
#PBS -l select={nodes}
#PBS -l walltime={walltime}
#PBS -l filesystems=flare
#PBS -q {queue}
#PBS -A {project}
#PBS -N {job_name}
# Generated by batch/generate.py — do not hand-edit (re-generate instead).
#   case={case} size={size} lattice={lattice} nodes={nodes} ppn={ppn} dim={dim} stages={stages_str} warmup={warmup} steps={steps}
# Submit with: qsub {out_rel}

set -e
cd ${{PBS_O_WORKDIR:-$(dirname $0)/../..}}
REPO_ROOT=$PWD

# Baked-in parameters (no env vars needed)
CASE="{case}"
SIZE="{size}"
LATTICE="{lattice}"
NNODES={nodes}
PPN={ppn}
DIM={dim}
NCELLS="{ncells}"
STAGES="{stages_str}"
WARMUP={warmup}
STEPS={steps}
BUILD_OPTS="DIM={dim} USE_MPI={build_use_mpi} USE_SYCL={build_use_sycl} COMP={build_comp}"
FLARE_ROOT="{flare_root}"

echo "Aurora bench: case=$CASE size=$SIZE lattice=$LATTICE nodes=$NNODES ppn=$PPN dim=$DIM ncells=$NCELLS stages=$STAGES warmup=$WARMUP steps=$STEPS"
echo "Job: $PBS_JOBID on $(hostname) at $(date)"
echo "Repo: $REPO_ROOT  Flare: $FLARE_ROOT  PWD: $PWD"

if command -v module &>/dev/null; then
  module use /soft/modulefiles || true
  module load cmake || true
fi

export MPICH_GPU_SUPPORT_ENABLED=1
export FI_CXI_ATS=0
export ZE_FLAT_DEVICE_HIERARCHY=COMPOSITE
export OMP_NUM_THREADS=1
export HTTP_PROXY=http://proxy.alcf.anl.gov:3128
export HTTPS_PROXY=http://proxy.alcf.anl.gov:3128
export http_proxy=http://proxy.alcf.anl.gov:3128
export https_proxy=http://proxy.alcf.anl.gov:3128

"""

# These blocks go through .format(validate_compile=...) / .format(validate_run=...)
# so shell ${VAR} must be written as ${{VAR}} to survive Python formatting.
COMPILING_BLOCK = """
# ── Stage: compiling ──────────────────────────────────────────────────
echo "=== COMPILING $CASE (DIM=$DIM) ==="
if [ -d "benchmarks/$CASE" ]; then
  make -C benchmarks/$CASE -j4 $BUILD_OPTS
  BENCH_EXE_NAME=$(make -C benchmarks/$CASE $BUILD_OPTS print-executable 2>/dev/null | sed -n 's/^executable is \\(.*\\)$/\\1/p')
  echo "Built benchmarks/$CASE/$BENCH_EXE_NAME"
else
  echo "No bench for $CASE (validate-only) — skipping bench build"
fi
{validate_compile}
echo "Compile stage done."
"""

VALIDATE_COMPILE_SNIPPET = """if [ -d "{validate_dir}" ]; then
  make -C {validate_dir} -j4 DIM=$DIM USE_MPI=TRUE USE_SYCL=TRUE COMP=intel || make -C {validate_dir} -j4 DIM=$DIM
  echo "Built {validate_dir}/test_*.ex"
fi"""

VALIDATING_BLOCK = """
# ── Stage: validating ─────────────────────────────────────────────────
echo "=== VALIDATING $CASE ==="
{validate_run}
echo "Validate stage done."
"""

VALIDATE_RUN_KNOWN = """if [ -d "{validate_dir}" ]; then
  echo "Running validate from {validate_dir} (upstream regression)"
  VALIDATE_EXE=$(ls {validate_dir}/test_*.ex {validate_dir}/*.ex 2>/dev/null | head -1)
  if [ -z "$VALIDATE_EXE" ]; then
    echo "ERROR: no validate exe in {validate_dir} — did compiling stage run?"; exit 1
  fi
  echo "Validate exe: $VALIDATE_EXE"
  # Pick inputs file: 3D cases use inputs3d when present
  VALIDATE_INPUTS="{validate_dir}/inputs"
  VALIDATE_INPUTS_NAME="inputs"
  if [ "$DIM" -eq 3 ] && [ -f "{validate_dir}/inputs3d" ]; then
    VALIDATE_INPUTS="{validate_dir}/inputs3d"
    VALIDATE_INPUTS_NAME="inputs3d"
  fi
  echo "Validate inputs: $VALIDATE_INPUTS"
  # Stage validate to flare (log + any plotfiles live on Lustre)
  VALIDATE_FLARE_DIR="$FLARE_ROOT/${{CASE}}_${{SIZE}}_validate_${{PBS_JOBID%%.*}}"
  # When not under PBS (local --dry-run) PBS_JOBID is empty — fall back to repo-local dir
  if [ -z "${{PBS_JOBID}}" ]; then
    VALIDATE_FLARE_DIR="$REPO_ROOT/validate_${{CASE}}_${{SIZE}}"
  fi
  mkdir -p "$VALIDATE_FLARE_DIR"
  # Copy exe + inputs to flare run dir
  cp "$VALIDATE_EXE" "$VALIDATE_FLARE_DIR"/
  cp "$VALIDATE_INPUTS" "$VALIDATE_FLARE_DIR"/ 2>/dev/null || cp -r "$VALIDATE_INPUTS" "$VALIDATE_FLARE_DIR"/ 2>/dev/null || true
  echo "Validate flare dir: $VALIDATE_FLARE_DIR (pwd before: $PWD)"
  # Validate runs are small (N=32-64) — single rank is sufficient
  VALIDATE_EXE_NAME=$(basename "$VALIDATE_EXE")
  if [ "$NNODES" -gt 1 ]; then
    (cd "$VALIDATE_FLARE_DIR" && mpiexec -n 1 --ppn 1 ./$VALIDATE_EXE_NAME $VALIDATE_INPUTS_NAME 2>&1 | tee validate_${{CASE}}_${{SIZE}}.log)
  else
    (cd "$VALIDATE_FLARE_DIR" && ./$VALIDATE_EXE_NAME $VALIDATE_INPUTS_NAME 2>&1 | tee validate_${{CASE}}_${{SIZE}}.log)
  fi
  echo "Validate log: $VALIDATE_FLARE_DIR/validate_${{CASE}}_${{SIZE}}.log"
else
  echo "No validate directory for $CASE at {validate_dir} — skipping"
fi"""

VALIDATE_RUN_NONE = """echo "No validate available for $CASE — skipping (no benchmarks/$CASE/validate nor external fallback)" """

# Performance block is appended verbatim (not .format'd), so shell vars use single braces.
PERFORMANCE_BLOCK = """
# ── Stage: performance ────────────────────────────────────────────────
echo "=== PERFORMANCE $CASE size=$SIZE lattice=$LATTICE nodes=$NNODES ==="
if [ ! -d "benchmarks/$CASE" ]; then
  echo "No bench for $CASE (validate-only case) — skipping performance stage"
else
EXE_NAME=$(make -C benchmarks/$CASE $BUILD_OPTS print-executable 2>/dev/null | sed -n 's/^executable is \\(.*\\)$/\\1/p')
if [ -z "$EXE_NAME" ]; then echo "ERROR: could not determine bench exe name (make print-executable failed)"; exit 1; fi
BENCH_EXE="benchmarks/$CASE/$EXE_NAME"
echo "Resolved bench exe: $BENCH_EXE (from make print-executable)"

# Fallback build if compiling stage was not included and exe is missing
if [ ! -x "$BENCH_EXE" ]; then
  echo "bench exe $BENCH_EXE not found — building on compute node (prefer compiling stage)"
  make -C benchmarks/$CASE -j4 $BUILD_OPTS
fi
if [ ! -x "$BENCH_EXE" ]; then echo "ERROR: bench exe $BENCH_EXE missing after build; found:"; ls -l benchmarks/$CASE/*.ex 2>&1 || echo "(no *.ex in benchmarks/$CASE)"; exit 1; fi
INPUTS="benchmarks/$CASE/inputs.bench"
echo "Inputs: $INPUTS  ncells=$NCELLS  warmup=$WARMUP steps=$STEPS (max_step=$((WARMUP+STEPS)))"

# Stage to flare: copy exe + inputs to Lustre and run there
RUN_DIR="$FLARE_ROOT/${CASE}_${SIZE}_${NNODES}nodes_${PBS_JOBID%%.*}"
if [ -z "$PBS_JOBID" ]; then
  # Not under PBS (local test) — keep run dir under repo so the snippet is still runnable
  RUN_DIR="$REPO_ROOT/run_${CASE}_${SIZE}_${NNODES}"
fi
mkdir -p "$RUN_DIR"
cp "$BENCH_EXE" "$RUN_DIR"/
cp "$INPUTS" "$RUN_DIR"/
echo "Staged to flare: $RUN_DIR"
echo "  PWD before cd: $PWD  (REPO_ROOT=$REPO_ROOT)"
ls -lh "$RUN_DIR"/ | sed 's/^/  staged: /'
echo "  df $RUN_DIR:"; df -h "$RUN_DIR" 2>&1 | sed 's/^/  /' || true
cd "$RUN_DIR"
echo "  PWD after cd: $PWD"

# GPU binding per https://docs.alcf.anl.gov/aurora/running-jobs-aurora/#binding-mpi-ranks-to-gpus
# Each Aurora node has 6 PVC GPUs x 2 tiles = 12 tiles. PPN=12 is "explicit scaling"
# (1 rank/tile) via gpu_tile_compact.sh; PPN=6 is "implicit" (1 rank/GPU) via
# gpu_dev_compact.sh. The wrapper sets ZE_AFFINITY_MASK per rank (requires
# ZE_FLAT_DEVICE_HIERARCHY=COMPOSITE, the Aurora default). The --cpu-bind list
# below reserves cores 0 and 52 for the OS (Mar 2025+) and gives each rank
# compact cores on its socket.
if [ "$PPN" -eq 12 ]; then
  CPU_BIND="--cpu-bind=list:1-8:9-16:17-24:25-32:33-40:41-48:53-60:61-68:69-76:77-84:85-92:93-100"
  GPU_WRAPPER="gpu_tile_compact.sh"
elif [ "$PPN" -eq 6 ]; then
  CPU_BIND="--cpu-bind=list:1-16:17-32:33-48:53-68:69-84:85-100"
  GPU_WRAPPER="gpu_dev_compact.sh"
else
  # Generic fallback: let MPICH place ranks, but still bind via wrapper
  CPU_BIND="--cpu-bind=depth --depth=8"
  GPU_WRAPPER="gpu_tile_compact.sh"
fi

mpiexec -n $((NNODES * PPN)) --ppn $PPN $CPU_BIND $GPU_WRAPPER \\
  ./$EXE_NAME inputs.bench grid.ncells="$NCELLS" lbm.lattice_type=$LATTICE amr.plot_int=-1 sim.max_step=$((WARMUP+STEPS)) bench.warmup=$WARMUP 2>&1 | tee run.log

grep BENCH_RESULT run.log || echo "No BENCH_RESULT found"

source $HOME/pyvenv_lbm/bin/activate
python3 "$REPO_ROOT/perf.py" log --test "$CASE" --lattice "$LATTICE" --ncells "$NCELLS" --nprocs $((NNODES * PPN)) --nnodes $NNODES --ppn $PPN --inputs "$RUN_DIR/inputs.bench" --log "$RUN_DIR/run.log" --steps $STEPS --warmup $WARMUP --compiler intel || echo "WARNING: perf.py log failed (exit $?)"
echo "Performance stage done: $RUN_DIR/run.log (also in repo .cache/perf.db; history.jsonl only when muphfasa is on main)"
fi
"""


def resolve_validate_dir(case: str) -> str | None:
    primary, secondary = VALIDATE_MAP.get(case, (None, None))
    if primary and (REPO_ROOT / primary).is_dir():
        return primary
    if secondary and (REPO_ROOT / secondary).is_dir():
        return secondary
    return primary or secondary


def parse_args():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--case", "--cases", dest="cases", nargs="+", required=True,
                   choices=list(CASE_DIM.keys()), help="benchmark case(s)")
    p.add_argument("--nodes", nargs="+", type=int, required=True, help="node count(s), e.g. --nodes 2 4")
    p.add_argument("--size", type=int, default=None, help="N per side (alias for --sizes with one value)")
    p.add_argument("--sizes", nargs="+", type=int, default=None, help="N per side, e.g. --sizes 2048 4096")
    p.add_argument("--lattice", type=str, default=None, help="lattice, e.g. D2Q9 (default per case)")
    p.add_argument("--ppn", type=int, default=12, help="ranks per node (default 12 = 6 GPUs x 2 tiles)")
    p.add_argument("--queue", type=str, default=None, help="PBS queue (default: auto from nodes — debug 1-2, debug-scaling 2-256, prod 256+)")
    p.add_argument("--walltime", type=str, default="00:30:00")
    p.add_argument("--project", type=str, default="muphfasa", help="ALCF project allocation")
    p.add_argument("--stages", nargs="+", choices=ALL_STAGES, default=ALL_STAGES,
                   help="which stages to include (default: all three; pick any subset in any order)")
    p.add_argument("--warmup", type=int, default=None, help="warmup steps (default per dim: 2D=100, 3D=50)")
    p.add_argument("--steps", type=int, default=None, help="timed steps (default per dim: 2D=2000, 3D=500)")
    p.add_argument("--flare-root", type=str, default=None, help="flare run root (default /flare/<project>/$USER/muphfasa-benchmarking-runs)")
    p.add_argument("--outdir", type=Path, default=REPO_ROOT / "batch" / "generated",
                   help="output directory (default batch/generated/)")
    p.add_argument("--product", action=argparse.BooleanOptionalAction, default=True,
                   help="cartesian product of --cases x --nodes x --sizes (default true); --no-product zips them")
    p.add_argument("--dry-run", action="store_true", help="print paths without writing")
    return p.parse_args()


QUEUE_LIMITS = {
    "debug": (1, 2),
    "debug-scaling": (2, 256),
    "prod": (256, 10624),
    "capacity": (1, 16),
    "visualization": (1, 32),
}

def auto_queue(nodes: int) -> str:
    if nodes <= 2:
        return "debug"
    if nodes <= 256:
        return "debug-scaling"
    return "prod"

def validate_queue(queue: str, nodes: int):
    if queue not in QUEUE_LIMITS:
        return
    lo, hi = QUEUE_LIMITS[queue]
    if not (lo <= nodes <= hi):
        suggestion = auto_queue(nodes)
        raise SystemExit(
            f"queue '{queue}' requires {lo}-{hi} nodes, but --nodes={nodes} was requested. "
            f"Use -q {suggestion} for {nodes} nodes (see https://docs.alcf.anl.gov/aurora/running-jobs-aurora/#queues) "
            f"or pass --queue {suggestion} explicitly. prod requires ≥256 nodes."
        )


def main():
    args = parse_args()

    seen = set()
    stages = []
    for s in args.stages:
        if s not in seen:
            seen.add(s)
            stages.append(s)
    if not stages:
        raise SystemExit("--stages requires at least one of: " + ", ".join(ALL_STAGES))
    order = {s: i for i, s in enumerate(ALL_STAGES)}
    stages_sorted = sorted(stages, key=lambda s: order[s])

    if args.sizes is not None:
        sizes = args.sizes
    elif args.size is not None:
        sizes = [args.size]
    else:
        sizes = [None]

    cases = args.cases
    nodes_list = args.nodes

    if args.product:
        combos = list(itertools.product(cases, nodes_list, sizes))
    else:
        max_len = max(len(cases), len(nodes_list), len(sizes))
        def broadcast(lst):
            if len(lst) == 1:
                return lst * max_len
            if len(lst) != max_len:
                raise SystemExit(f"--no-product requires equal lengths or singletons, got cases={cases} nodes={nodes_list} sizes={sizes}")
            return lst
        combos = list(zip(broadcast(cases), broadcast(nodes_list), broadcast(sizes)))

    args.outdir.mkdir(parents=True, exist_ok=True)
    written = []

    for case, nodes, size in combos:
        queue = args.queue or auto_queue(nodes)
        validate_queue(queue, nodes)
        dim = CASE_DIM[case]
        lattice = args.lattice or CASE_LATTICE[case]
        if size is None:
            size = 64
        ncells = f"{size} {size}" if dim == 2 else f"{size} {size} {size}"
        validate_dir = resolve_validate_dir(case)

        # Per-dim timing defaults (overridable via --warmup/--steps)
        warmup = args.warmup if args.warmup is not None else DEFAULT_WARMUP[dim]
        steps  = args.steps  if args.steps  is not None else DEFAULT_STEPS[dim]

        flare_root = args.flare_root or f"/flare/{args.project}/$USER/muphfasa-benchmarking-runs"

        stages_str = " ".join(stages_sorted)
        stages_tag = "" if set(stages_sorted) == set(ALL_STAGES) else "_" + "_".join(stages_sorted)
        job_name = f"{case}_{size}_{nodes}nodes{stages_tag}"
        fname = f"{case}_{size}_{nodes}nodes{stages_tag}.sh"
        out_path = args.outdir / fname
        out_rel = os.path.relpath(out_path, REPO_ROOT)

        blocks = []

        if "compiling" in stages_sorted:
            if validate_dir and (REPO_ROOT / validate_dir).is_dir():
                vcomp = VALIDATE_COMPILE_SNIPPET.format(validate_dir=validate_dir)
            else:
                vcomp = ""
            blocks.append(COMPILING_BLOCK.format(validate_compile=vcomp))

        if "validating" in stages_sorted:
            if validate_dir:
                vrun = VALIDATE_RUN_KNOWN.format(validate_dir=validate_dir)
            else:
                vrun = VALIDATE_RUN_NONE
            blocks.append(VALIDATING_BLOCK.format(validate_run=vrun))

        if "performance" in stages_sorted:
            blocks.append(PERFORMANCE_BLOCK)

        header = HEADER_TMPL.format(
            nodes=nodes, walltime=args.walltime, queue=queue, project=args.project,
            job_name=job_name, case=case, size=size, lattice=lattice, ppn=args.ppn,
            dim=dim, ncells=ncells, stages_str=stages_str, out_rel=out_rel,
            warmup=warmup, steps=steps,
            build_use_mpi=BUILD_USE_MPI, build_use_sycl=BUILD_USE_SYCL, build_comp=BUILD_COMP,
            flare_root=flare_root,
        )
        content = header + "".join(blocks)
        if not content.endswith("\n"):
            content += "\n"

        if args.dry_run:
            print(f"[dry-run] would write {out_rel} stages={stages_str}")
            continue
        out_path.write_text(content)
        out_path.chmod(0o755)
        written.append(out_rel)
        print(f"Wrote {out_rel}  (case={case} size={size} nodes={nodes} lattice={lattice} stages={stages_str} warmup={warmup} steps={steps})")

    if written:
        print(f"\nSubmit with:  qsub {' '.join(written)}")
        print(f"Or individually: qsub {written[0]}")

if __name__ == "__main__":
    main()
